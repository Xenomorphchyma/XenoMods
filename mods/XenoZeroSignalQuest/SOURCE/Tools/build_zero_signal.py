def media(img: str | None = None) -> QuestMedia:
    return QuestMedia(img=img, sound=None, track=None)


def parameter(
    name: str,
    minimum: int,
    maximum: int,
    start: int,
    *,
    visible: bool = False,
    money: bool = False,
    label: str | None = None,
) -> QuestParameter:
    return QuestParameter(
        minimum=minimum,
        maximum=maximum,
        param_type=0,
        show_when_zero=visible,
        crit_type=1,
        active=visible,
        is_money=money,
        name=name,
        showing_info=(QuestShowingRange(minimum, maximum, label or f"{name}: <>"),),
        crit_value_text="",
        starting_formula=f"[{start}]",
        media=media(),
    )


