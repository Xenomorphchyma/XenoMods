def expanded_scene_text(name: str, text: str, loc_id: int, location_type: int) -> str:
    base = text.strip()
    if location_type not in (0, 1):
        return base
    if name in BESPOKE_SCENE_DETAILS:
        return base + "\n\n" + BESPOKE_SCENE_DETAILS[name]
    details = (
        SENSORY_DETAILS[(loc_id - 1) % len(SENSORY_DETAILS)],
        TECHNICAL_DETAILS[((loc_id - 1) * 5) % len(TECHNICAL_DETAILS)],
        RANGER_OBSERVATIONS[((loc_id - 1) * 11) % len(RANGER_OBSERVATIONS)],
        CORPORATE_ECHOES[((loc_id - 1) * 7) % len(CORPORATE_ECHOES)],
    )
    return base + "\n\n" + " ".join(details)


def L(name: str, text: str, img: str, location_type: int = 0) -> None:
    loc_id = len(locations) + 1
    location_ids[name] = loc_id
    locations.append(
        QuestLocation(
            day_passed=False,
            x=80 + ((loc_id - 1) % 12) * 95,
            y=80 + ((loc_id - 1) // 12) * 75,
            id=loc_id,
            max_visits=0,
            location_type=location_type,
            parameter_changes=changes(),
            texts=(QuestLocationText(text=expanded_scene_text(name, text, loc_id, location_type), media=media(img)),),
            text_by_formula=False,
            text_select_formula="",
        )
    )


def J(
    source: str,
    target: str,
    text: str,
    *,
    description: str = "",
    formula: str = "",
    updates: dict[int, str] | None = None,
    limit: int = 0,
    img: str | None = None,
    priority: float = 1.0,
) -> None:
    from_id = location_ids[source]
    orders[from_id] += 1
    jumps.append(
        QuestJump(
            priority=priority,
            day_passed=False,
            id=len(jumps) + 1,
            from_location_id=from_id,
            to_location_id=location_ids[target],
            always_show=False,
            jumping_count_limit=limit,
            showing_order=orders[from_id],
            parameter_changes=changes(updates),
            parameter_conditions=conditions(),
            formula_to_pass=formula,
            text=text,
            description=description.strip(),
            media=media(img),
        )
    )


