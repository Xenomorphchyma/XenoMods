def empty_change() -> QuestParameterChange:
    return QuestParameterChange(
        change=0,
        showing_type=0,
        change_type=1,
        changing_formula="",
        crit_text="",
        media=media(),
    )


def changes(values: dict[int, str] | None = None) -> tuple[QuestParameterChange, ...]:
    result = [empty_change() for _ in range(PARAM_COUNT)]
    for index, formula in (values or {}).items():
        result[index - 1] = QuestParameterChange(
            change=0,
            showing_type=0,
            change_type=3,
            changing_formula=formula,
            crit_text="",
            media=media(),
        )
    return tuple(result)


def conditions() -> tuple[QuestParameterCondition, ...]:
    return tuple(
        QuestParameterCondition(
            must_from=item.minimum,
            must_to=item.maximum,
            equal_values=(),
            equal_flag=False,
            mod_values=(),
            mod_flag=False,
        )
        for item in PARAMETERS
    )


