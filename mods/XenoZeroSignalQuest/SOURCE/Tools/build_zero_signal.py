def main() -> None:
    output = MOD_ROOT / "SOURCE" / "Quest" / "ZeroSignal.quest.json"
    review_output = MOD_ROOT / "SOURCE" / "Quest" / "ZeroSignal.review.txt"
    document = build_document()
    output.write_text(
        json.dumps(document.as_dict(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    review_lines = [
        "НУЛЕВОЙ СИГНАЛ — РЕДАКТОРСКАЯ ВЫГРУЗКА",
        "",
        "=== ТЕКСТ ВЫДАЧИ ===",
        document.task_text,
        "",
        "=== ОБЩИЙ УСПЕШНЫЙ ЭПИЛОГ ===",
        document.success_text,
        "",
        "=== ЛОКАЦИИ И ВЫБОРЫ ===",
    ]
    jumps_by_source: defaultdict[int, list[QuestJump]] = defaultdict(list)
    for jump in document.jumps:
        jumps_by_source[jump.from_location_id].append(jump)
    reverse_names = {value: key for key, value in location_ids.items()}
    for location in document.locations:
        name = reverse_names[location.id]
        review_lines.extend(
            [
                "",
                f"--- {location.id:03d} {name} | type={location.location_type} | image={location.texts[0].media.img} ---",
                location.texts[0].text,
                "",
                "ВЫБОРЫ:",
            ]
        )
        for jump in sorted(jumps_by_source[location.id], key=lambda item: item.showing_order):
            condition = f" [если {jump.formula_to_pass}]" if jump.formula_to_pass else ""
            review_lines.append(f"  -> {reverse_names[jump.to_location_id]}: {jump.text}{condition}")
    review_output.write_text("\n".join(review_lines) + "\n", encoding="utf-8")
    text_parts = [document.task_text, document.success_text]
    text_parts.extend(item.text for loc in document.locations for item in loc.texts)
    text_parts.extend(value for jump in document.jumps for value in (jump.text, jump.description))
    words = sum(len(value.split()) for value in text_parts)
    print(
        json.dumps(
            {
                "output": str(output),
                "review_output": str(review_output),
                "parameters": len(document.parameters),
                "locations": len(document.locations),
                "jumps": len(document.jumps),
                "words": words,
                "death_locations": sum(loc.location_type == 5 for loc in document.locations),
                "success_locations": sum(loc.location_type == 3 for loc in document.locations),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
